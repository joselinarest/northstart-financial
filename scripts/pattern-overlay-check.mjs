import assert from 'node:assert/strict';
import {drawPatternOverlay,patternColor} from '../lib/draw-pattern-overlay.ts';
const view=[{time:'2026-09-21'},{time:'2026-09-22'}];
const p={name:'Test',direction:'UP',validation:'WARNING',startTime:view[0].time,endTime:view[1].time,confirmationLevel:110,invalidationLevel:95,anchors:[{time:view[0].time,price:100},{time:view[1].time,price:105}]};
const calls=[],g=new Proxy({},{get:(_,key)=>(...args)=>calls.push([key,...args]),set:(_,key,value)=>{calls.push([key,value]);return true}});
const plot={left:10,right:250,top:20,bottom:200,cw:100,py:value=>200-value};
assert.equal(drawPatternOverlay(g,p,view,plot),true);
assert(calls.some(c=>c[0]==='fillText'&&c[1].includes('Pattern trigger $110.00')));
assert(calls.some(c=>c[0]==='fillText'&&c[1].includes('Pattern invalidation $95.00')));
assert(calls.some(c=>c[0]==='clip'));
assert.equal(calls.filter(c=>c[0]==='arc').length,2);
assert.equal(patternColor(p),'#4ade80');
assert.equal(patternColor({...p,direction:'DOWN'}),'#fb7185');
assert.equal(patternColor({...p,direction:'NEUTRAL'}),'#fbbf24');
assert.equal(patternColor({...p,validation:'FAIL'}),'#94a3b8');
const before=calls.length;
assert.equal(drawPatternOverlay(g,p,[{time:'2025-01-01'}],plot),false);
assert.equal(calls.length,before);
console.log('PASS: pattern colors, anchors, trigger/invalidation labels and offscreen clipping.');
